const assert=require('assert'),fs=require('fs'),vm=require('vm');
const html=fs.readFileSync('app/index.html','utf8');
const runtime=html.split('// Owned UI text')[1].split('const $=')[0];
const node=()=>({textContent:'',dataset:{},isConnected:true,attributes:{},setAttribute(k,v){this.attributes[k]=v;},getAttribute(k){return this.attributes[k];}});
const own=node();own.dataset.i18n='youtube.search';const query=node();query.attributes['data-i18n-placeholder']='youtube.query';
const document={documentElement:{},getElementById:()=>null,querySelectorAll(selector){return selector==='[data-i18n]'?[own]:selector==='[data-i18n-placeholder]'?[query]:[];}};
let loads=0;const context=vm.createContext({document,window:{},loadRecommendations:()=>loads++});
vm.runInContext('// Owned UI text'+runtime,context);
const catalogs={};for(const locale of ['pt-BR','en-US'])catalogs[locale]=JSON.parse(fs.readFileSync('i18n/'+locale+'.json','utf8'));
context.window.orbitzSetLanguage({locale:'pt-BR',catalog:catalogs['pt-BR']});assert.equal(own.textContent,'Buscar');
const external=node();context.uiRaw(external,'Título do usuário · autor externo');
const status=node();context.uiText(status,'youtube.loading_comments');
context.window.orbitzSetLanguage({locale:'en-US',catalog:catalogs['en-US']});
assert.equal(own.textContent,'Search');assert.equal(status.textContent,'Loading comments…');assert.equal(query.attributes.placeholder,'Search videos or paste a YouTube link');
assert.equal(external.textContent,'Título do usuário · autor externo');assert.equal(loads,1,'language switch never restarts playback/recommendations');
const current=node();context.uiText(current,'youtube.loading_video');context.uiRaw(current,'EXTERNAL VIDEO TITLE');
context.window.orbitzSetLanguage({locale:'pt-BR',catalog:catalogs['pt-BR']});assert.equal(current.textContent,'EXTERNAL VIDEO TITLE');
status.isConnected=false;context.uiPrune();
assert(!vm.runInContext('uiBindings',context).has(status));
assert(!html.includes("toLocaleDateString('pt-BR')"));
assert(html.includes('toLocaleDateString(uiLocale)'));assert(html.includes('toLocaleString(uiLocale)'));
console.log('OK: live YouTube UI/attributes/status, explicit locale dates/numbers, external text and playback preserved; detached bindings pruned.');
